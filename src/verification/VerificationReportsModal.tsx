import React, { useState } from "react";
import { Finding, Target, ValidationRecord } from "../types";
import { VerificationKpis } from "./types";
import { X, Download, Copy, Check, FileText, ShieldCheck } from "lucide-react";

interface VerificationReportsModalProps {
  isOpen: boolean;
  onClose: () => void;
  target?: Target | null;
  findings: Finding[];
  records: ValidationRecord[];
  kpis: VerificationKpis;
}

export const VerificationReportsModal: React.FC<VerificationReportsModalProps> = ({
  isOpen,
  onClose,
  target,
  findings,
  records,
  kpis,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const reportDate = new Date().toISOString();

  // Generate clean Markdown representation
  const generateMarkdown = () => {
    return `# AppSec Vulnerability Verification & Evidence Audit Report

**Generated:** ${reportDate}  
**Target:** ${target ? `${target.name} (${target.primary_url})` : "All Authorized Targets"}  
**Scope Boundary:** Authorized  
**Safe Non-Destructive Mode:** Enforced  

---

## 1. Executive Summary

- **Total Assessed Findings:** ${kpis.totalFindings}
- **Confirmed Vulnerabilities:** ${kpis.confirmed}
- **Refuted (False Positives):** ${kpis.falsePositives}
- **Potential (Awaiting / Incomplete Probing):** ${kpis.potential}
- **Inconclusive Probes:** ${kpis.inconclusive}
- **Simulated / Demo Records Isolated:** ${kpis.simulated}
- **Scan Errors / Target Timeouts:** ${kpis.scanErrors}
- **Verification Coverage Rate:** ${kpis.coveragePercentage}%
- **Average Verification Duration:** ${kpis.avgDurationMs} ms

---

## 2. Verification Methodology & Boundary Controls

1. **Passive & Non-Destructive Probing**: Evaluated HTTP response headers (CSP, HSTS, X-Content-Type-Options, CORS) via targeted HEAD/GET requests.
2. **Context-Aware Evidence Corroboration**: Required authentic injection response markers (e.g. back-end DBMS responses, reflection in specific DOM contexts) before confirming injection alerts.
3. **Defense-in-Depth Separation**: Isolated missing security headers (CWE-693) from active code execution vulnerabilities (CWE-79, CWE-89).
4. **Token Redaction**: Automatically scrubbed Authorization headers, session cookies, and API secrets from audit trails.

---

## 3. Verified Findings & Evidence Register

${
  findings.length === 0
    ? "_No findings registered in this project scope._\n"
    : findings
        .map((f, idx) => {
          const rec = records.find((r) => r.finding_id === f.id);
          return `### ${idx + 1}. [${f.severity.toUpperCase()}] ${f.title}
- **CWE:** ${f.cwe || "N/A"}
- **Affected Asset:** \`${f.affected_asset}\`
- **Detection Method:** ${f.detection_method || f.source_tool} (v${f.detector_version || f.tool_version})
- **Provenance Kind:** ${f.provenance_kind || (f.is_simulated ? "Simulated" : "Live")}
- **Verification Status:** **${f.verification_status || f.status}**
- **Confidence:** ${f.confidence}%
- **Observation Evidence:**
  > ${f.evidence || "No evidence recorded."}
${
  rec
    ? `- **Verification Test Method:** ${rec.test_method}
- **Actual Observation:** ${rec.actual_observation}
- **Supporting Evidence:** ${rec.supporting_evidence}
- **Contradicting Evidence:** ${rec.contradicting_evidence}
- **Duration:** ${rec.duration_ms} ms
`
    : "- _No active verification probe recorded for this finding._\n"
}`;
        })
        .join("\n")
}

---
*Generated by AppSec Nexus Vulnerability Verification Lab. All evidence is cryptographically tracked via SHA-256 finding fingerprints.*
`;
  };

  const handleCopy = () => {
    const md = generateMarkdown();
    if (navigator.clipboard) {
      navigator.clipboard.writeText(md);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `appsec-verification-report-${Date.now()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJson = () => {
    const payload = {
      title: "AppSec Vulnerability Verification Audit Bundle",
      generated_at: reportDate,
      target,
      kpis,
      findings,
      verification_records: records,
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `appsec-verification-bundle-${Date.now()}.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div
      style={{
        position: "fixed",
        inset: 0,
        backgroundColor: "rgba(0, 0, 0, 0.75)",
        backdropFilter: "blur(4px)",
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        zIndex: 1000,
        padding: "16px",
      }}
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
      role="dialog"
      aria-modal="true"
      aria-labelledby="report-modal-title"
    >
      <div
        className="card"
        style={{
          width: "100%",
          maxWidth: "850px",
          height: "85vh",
          display: "flex",
          flexDirection: "column",
          background: "var(--bg-secondary)",
          border: "1px solid var(--border-color)",
          borderRadius: "10px",
          padding: "24px",
          boxShadow: "0 16px 40px rgba(0, 0, 0, 0.5)",
          color: "var(--text-main)",
        }}
      >
        {/* Header */}
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "16px" }}>
          <div style={{ display: "flex", alignItems: "center", gap: "10px" }}>
            <div style={{ padding: "6px", borderRadius: "6px", background: "rgba(16, 185, 129, 0.12)", color: "var(--accent-emerald, #10b981)" }}>
              <ShieldCheck size={20} />
            </div>
            <div>
              <h2 id="report-modal-title" style={{ margin: 0, fontSize: "1.1rem", fontWeight: 700 }}>
                Vulnerability Verification Audit Report
              </h2>
              <p style={{ margin: 0, fontSize: "0.8rem", color: "var(--text-muted)" }}>
                Exportable evidence audit bundle covering live validations, refutations, and provenance.
              </p>
            </div>
          </div>
          <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
            <button
              type="button"
              onClick={handleCopy}
              className="btn btn-secondary"
              style={{ fontSize: "0.8rem", padding: "6px 10px" }}
              title="Copy Markdown"
            >
              {copied ? <Check size={14} color="var(--accent-emerald)" /> : <Copy size={14} />} {copied ? "Copied!" : "Copy"}
            </button>
            <button
              type="button"
              onClick={handleDownloadMarkdown}
              className="btn btn-secondary"
              style={{ fontSize: "0.8rem", padding: "6px 10px" }}
              title="Download Markdown Report"
            >
              <Download size={14} /> Markdown (.md)
            </button>
            <button
              type="button"
              onClick={handleDownloadJson}
              className="btn btn-secondary"
              style={{ fontSize: "0.8rem", padding: "6px 10px" }}
              title="Download JSON Bundle"
            >
              <FileText size={14} /> JSON (.json)
            </button>
            <button
              type="button"
              onClick={onClose}
              className="btn btn-secondary"
              style={{ padding: "6px 8px" }}
              aria-label="Close report modal"
            >
              <X size={16} />
            </button>
          </div>
        </div>

        {/* Report Preview */}
        <div
          style={{
            flex: 1,
            overflowY: "auto",
            background: "var(--bg-primary)",
            border: "1px solid var(--border-color)",
            borderRadius: "6px",
            padding: "16px 20px",
            fontFamily: "monospace",
            fontSize: "0.82rem",
            whiteSpace: "pre-wrap",
            lineHeight: 1.5,
            color: "var(--text-main)",
          }}
        >
          {generateMarkdown()}
        </div>

        {/* Footer */}
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginTop: "16px", fontSize: "0.78rem", color: "var(--text-dim)" }}>
          <span>Coverage: {kpis.coveragePercentage}% ({kpis.confirmed + kpis.falsePositives} of {kpis.totalFindings} verified)</span>
          <button type="button" onClick={onClose} className="btn btn-secondary" style={{ padding: "6px 14px" }}>
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
